def main(chs):
    for c in chs:
        p = D / c / 'episode.json'
        ep = json.loads(p.read_text())
        ep['shots'] = [{'id': i, 'size': s, 'key': k, 'note': n} for i, s, _, k, n in E[c]]
        ep['edit'] = [{'shot': i, 'at': cue} for i, _, cue, _, _ in E[c]]
        if c == 'c07':
            ep['tail'] = 15
        p.write_text(json.dumps(ep, indent=1, ensure_ascii=False) + '\n')
        print(c, len(E[c]), 'shots')
main(sys.argv[1:] or list(E))
